def to_part(partid, auto_unknown = True):
    manufacturer_name = jep106.name_get(partid.jep106_bank, partid.jep106_id)
    manufacturer_parts = part_names.get((partid.jep106_bank, partid.jep106_id), {})
    try:
        return manufacturer_parts[partid.part_no]
    except:
        if not auto_unknown:
            throw
            
    return Part("Unknown part %04x" % partid.part_no)
        

def pretty_name(partid, auto_unknown = True):
    part = to_part(partid, auto_unknown)
    manufacturer_name = jep106.name_get(partid.jep106_bank, partid.jep106_id)
    return "%s %s v%d" % (manufacturer_name, part.name, partid.revision)
