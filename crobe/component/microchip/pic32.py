class Pic32Tap(EjtagTap):
    # Param EJ1, TTCKCYC
    max_freq = 1 / 25e-9

    IDCODE = 1
    COMMAND = 7
    SW_MTAP = 4
    SW_ETAP = 5

    MTAP_STATUS        = 0x00
    MTAP_ASSERT_RST    = 0xD1
    MTAP_DEASSERT_RST  = 0xD0
    MTAP_ERASE         = 0xFC
    MTAP_FLASH_ENABLE  = 0xFE
    MTAP_FLASH_DISABLE = 0xFD

    def __init__(self, port, index, idcode):
        EjtagTap.__init__(self, port, index, idcode)
        self.__mode = None

    def start(self):
        st = self.mtap_shift(self.MTAP_STATUS, 0, 8)

        self.logger.info("MTAP Status: 0x%02x", st)
        self.logger.info("Implementer code: 0x%08x", self.dr_shift(self.IMPCODE, 0, 32))

        jtag.Tap.start(self)

    def mtap_shift(self, ir, dr, length = None, read_tdo = True):
        ops = []
        if self.__mode != 'm':
            ops.append(self.cmd_dr_shift(self.SW_MTAP, None))
            self.__mode = 'm'
        ops.append(self.cmd_dr_shift(self.COMMAND, ir, 8, read_tdo = False))
        ops.append(self.cmd_dr_shift(self.COMMAND, dr, length, read_tdo))
        self.execute(ops)
        if read_tdo:
            return ops[-1].tdo

    def dr_shift(self, ir, dr, length = None, read_tdo = True):
        ops = []
        if self.__mode != 'e':
            ops.append(self.cmd_dr_shift(self.SW_ETAP, None))
            self.__mode = 'e'
        ops.append(self.cmd_dr_shift(ir, dr, length, read_tdo))
        self.execute(ops)
        if read_tdo:
            return ops[-1].tdo

@jtag.Tap.db.register(*[PartId(0, 0x29, p) for p in parts.keys()])
class Pic32MZTap(Pic32Tap):
    def __init__(self, port, index, idcode):
        Pic32Tap.__init__(self, port, index, idcode)
        self.name = parts.get(self.idcode.part_no, "PIC32")
